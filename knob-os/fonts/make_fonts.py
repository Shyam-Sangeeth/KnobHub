"""Builds Knob OS's fonts (src/core/fonts/knob_font_<size>.c): LVGL's Montserrat Medium and built-in symbols, like
LVGL's own lv_font_montserrat_*, but with the characters song titles and names use beyond ASCII (accents, dashes,
curly quotes...). Needs Node.js; run from anywhere:  python knob-os/fonts/make_fonts.py

Screens are designed at 240 px and ask for fonts by their design size (ui::font(12)); each screen size (DIAMETERS)
gets those sizes scaled, and fonts.cpp maps one to the other. A new board size needs adding to DIAMETERS."""
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "core", "fonts")
CONVERTER = ["npx", "--yes", "lv_font_conv@1.5.3"]

ASCII = "0x20-0x7E"
# Latin-1 Supplement and Latin Extended-A (western and central European letters), dashes, quotes, ellipsis, bullet,
# per mille, guillemets, euro, trade mark.
TEXT = ASCII + ",0xA0-0x17F,0x2010-0x2027,0x2030,0x2039-0x203A,0x20AC,0x2122"
# LVGL's built-in symbols (LV_SYMBOL_*), from scripts/built_in_font/built_in_font_gen.py.
SYMBOLS = ("61441,61448,61451,61452,61453,61457,61459,61461,61465,61468,61473,61478,61479,61480,61502,61507,61512,"
           "61515,61516,61517,61521,61522,61523,61524,61543,61544,61550,61552,61553,61556,61559,61560,61561,61563,"
           "61587,61589,61636,61637,61639,61641,61664,61671,61674,61683,61724,61732,61787,61931,62016,62017,62018,"
           "62019,62020,62087,62099,62212,62189,62810,63426,63650")
# Design sizes. The big one only shows numbers (the clock, a dial's value) and short words.
DESIGN_TEXT = [8, 12, 14, 16, 20, 24, 28]
DESIGN_BIG = [48]
DESIGN_DIGITS = [36, 60, 72, 96]
DIAMETERS = [240, 360, 480]  # the boards, and 480 for Knob Hub's preview
DESIGN = 240


def scaled(size, diameter):
    return (size * diameter + DESIGN // 2) // DESIGN


SIZES = {}
for d in DIAMETERS:
    for s in DESIGN_TEXT:
        SIZES[scaled(s, d)] = TEXT
for d in DIAMETERS:
    for s in DESIGN_BIG:
        SIZES.setdefault(scaled(s, d), ASCII + ",0xB0")
DIGIT_SIZES = sorted({scaled(s, d) for d in DIAMETERS for s in DESIGN_DIGITS})

os.makedirs(OUT, exist_ok=True)
for size, chars in sorted(SIZES.items()):
    name = f"knob_font_{size}"
    cmd = CONVERTER + ["--no-compress", "--no-prefilter", "--bpp", "4", "--size", str(size),
                       "--font", os.path.join(HERE, "Montserrat-Medium.ttf"), "-r", chars,
                       "--font", os.path.join(HERE, "FontAwesome5-Solid+Brands+Regular.woff"), "-r", SYMBOLS,
                       "--format", "lvgl", "--lv-font-name", name, "--force-fast-kern-format",
                       "-o", os.path.join(OUT, name + ".c")]
    subprocess.run(cmd, check=True, shell=os.name == "nt")
    print("wrote", name)

# Numbers bigger than the text sizes go (e.g. a counter filling the ring): digits and a few signs only, to stay small.
DIGITS = "0x20,0x25,0x2B-0x3A"  # space % + , - . / 0-9 :
for size in DIGIT_SIZES:
    name = f"knob_font_digits_{size}"
    cmd = CONVERTER + ["--no-compress", "--no-prefilter", "--bpp", "4", "--size", str(size),
                       "--font", os.path.join(HERE, "Montserrat-Medium.ttf"), "-r", DIGITS,
                       "--format", "lvgl", "--lv-font-name", name, "--force-fast-kern-format",
                       "-o", os.path.join(OUT, name + ".c")]
    subprocess.run(cmd, check=True, shell=os.name == "nt")
    print("wrote", name)

# fonts.h declares them all; fonts.cpp lists each screen size's set. A knob build defines KNOB_FONT_SET (its screen
# size) to keep only its own set, so the linker drops the other fonts; the simulator and the preview keep them all.
with open(os.path.join(OUT, "fonts.h"), "w", newline="\n") as f:
    f.write("#pragma once\n#include <lvgl.h>\n\n"
            "// Knob OS's fonts, generated by fonts/make_fonts.py: Montserrat Medium with LVGL's symbols and the characters\n"
            "// titles and names use beyond ASCII. Screens don't use them directly: ui::font and ui::digits pick the one for\n"
            "// a design size on this screen (see fonts.cpp).\n")
    for size in sorted(SIZES):
        f.write(f"LV_FONT_DECLARE(knob_font_{size})\n")
    f.write("// Digits and a few signs (space % + , - . / :) only, for big numbers.\n")
    for size in DIGIT_SIZES:
        f.write(f"LV_FONT_DECLARE(knob_font_digits_{size})\n")
    f.write("\nnamespace fonts {\n\n"
            "struct Entry {\n    int design;  // the size screens ask for (at 240 px)\n    int px;      // its size on this screen\n"
            "    const lv_font_t* font;\n};\n\n"
            "struct Set {\n    int diameter;\n    const Entry* text;  // ascending; the last ones are the big, ASCII-only sizes\n"
            "    int text_count;\n    const Entry* digits;\n    int digit_count;\n};\n\n"
            "// The fonts for each screen size in this build.\nconst Set* sets(int& count);\n\n}  // namespace fonts\n")
with open(os.path.join(OUT, "fonts.cpp"), "w", newline="\n") as f:
    f.write("// Generated by fonts/make_fonts.py.\n#include \"fonts.h\"\n\nnamespace fonts {\nnamespace {\n\n")
    for d in DIAMETERS:
        f.write(f"#if !defined(KNOB_FONT_SET) || KNOB_FONT_SET == {d}\n")
        text = [(s, scaled(s, d)) for s in DESIGN_TEXT + DESIGN_BIG]
        f.write(f"const Entry Text{d}[] = {{" + ", ".join(f"{{{s}, {p}, &knob_font_{p}}}" for s, p in text) + "};\n")
        digits = [(s, scaled(s, d)) for s in DESIGN_DIGITS]
        f.write(f"const Entry Digits{d}[] = {{" + ", ".join(f"{{{s}, {p}, &knob_font_digits_{p}}}" for s, p in digits) + "};\n")
        f.write("#endif\n")
    f.write("\nconst Set Sets[] = {\n")
    for d in DIAMETERS:
        f.write(f"#if !defined(KNOB_FONT_SET) || KNOB_FONT_SET == {d}\n"
                f"    {{{d}, Text{d}, sizeof Text{d} / sizeof Text{d}[0], Digits{d}, sizeof Digits{d} / sizeof Digits{d}[0]}},\n"
                "#endif\n")
    f.write("};\n\n}  // namespace\n\nconst Set* sets(int& count) {\n    count = sizeof Sets / sizeof Sets[0];\n"
            "    return Sets;\n}\n\n}  // namespace fonts\n")
print("wrote fonts.h, fonts.cpp")
